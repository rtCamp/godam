/**
 * Frontend script for the GoDAM Document block.
 *
 * Mounts the chrome-less pdf.js viewer over each rendered document. render.php emits only
 * the container plus a download link, so with JavaScript off — or if pdf.js fails to load —
 * the visitor still gets a usable link rather than an empty box.
 */

/**
 * WordPress dependencies
 */
import { createRoot, createElement } from '@wordpress/element';

/**
 * Render the PDF with the browser's built-in viewer.
 *
 * Only used when pdf.js could not be loaded at all — a chunk that 404s after a partial
 * deploy, or a browser that refuses the worker. The native viewer shows its own toolbar
 * (which is the whole reason we don't use it by default), but a preview with a toolbar beats
 * no preview.
 *
 * @param {HTMLElement} wrapper    The document container.
 * @param {string}      previewUrl URL of the PDF to display.
 */
function renderNativeFallback( wrapper, previewUrl ) {
	const object = document.createElement( 'object' );

	object.type = 'application/pdf';
	object.width = '100%';
	object.height = '100%';
	// Assigned as-is. The URL has already been through esc_url() server-side, and encodeURI()
	// would escape its percent signs a second time — turning a legitimate "%20" into "%2520"
	// and pointing the object at a path that does not exist.
	object.setAttribute( 'data', previewUrl );

	// Keep whatever fallback markup render.php emitted as the <object>'s own fallback, so a
	// browser with no PDF support still shows the download link.
	while ( wrapper.firstChild ) {
		object.appendChild( wrapper.firstChild );
	}

	wrapper.appendChild( object );
}

/**
 * Only http(s) URLs may be handed to the viewer or the fallback <object>.
 *
 * Blocks javascript:, data: and friends. The extension is deliberately NOT checked: a
 * preview URL is generated by GoDAM Central and need not end in `.pdf`.
 *
 * @param {string} url The URL to validate.
 * @return {boolean} True when the URL is safe to load.
 */
function isSafeUrl( url ) {
	try {
		const { protocol } = new URL( String( url ).trim(), window.location.href );

		return 'http:' === protocol || 'https:' === protocol;
	} catch ( e ) {
		return false;
	}
}

/**
 * Load the viewer chunk and mount it into a container.
 *
 * @param {HTMLElement} wrapper The document container.
 */
async function mountViewer( wrapper ) {
	const previewUrl = wrapper.getAttribute( 'data-godam-preview' );
	const title = wrapper.getAttribute( 'data-godam-title' ) || '';

	if ( ! previewUrl || ! isSafeUrl( previewUrl ) ) {
		return;
	}

	/*
	 * render.php's fallback paragraph, kept aside before React takes the container over.
	 *
	 * It carries the download link, and it is the only thing standing between a visitor and a
	 * dead end if the preview cannot be shown. Clearing the container to mount React destroys
	 * it, so the error path below has nothing to fall back to unless it is saved here first.
	 */
	const serverFallback = wrapper.firstElementChild
		? wrapper.firstElementChild.cloneNode( true )
		: null;

	let DocumentViewer;

	try {
		// Lazily imported so pdf.js — by far the heaviest thing this block loads — stays out
		// of the page until a document is actually about to be shown. Same pattern as the
		// player's plugin loader.
		( { default: DocumentViewer } = await import(
			/* webpackChunkName: "godam-pdf-viewer" */ './viewer'
		) );
	} catch ( error ) {
		renderNativeFallback( wrapper, previewUrl );
		return;
	}

	// React owns the container from here, so clear the server-rendered fallback first.
	wrapper.textContent = '';

	const root = createRoot( wrapper );

	/*
	 * One failure can be reported more than once: react-pdf routes onLoadError, onSourceError
	 * and onPassword to the viewer's error handler, which calls this back each time. Without
	 * the guard a second call unmounts an already-unmounted root and appends a second
	 * <object>, showing the visitor the document twice.
	 */
	let handledError = false;

	root.render(
		createElement( DocumentViewer, {
			url: previewUrl,
			title,
			onError: () => {
				// pdf.js loaded but could not render this file — most often a CORS failure on
				// the CDN, since pdf.js fetches over XHR where an <object> did not. Hand it to
				// the native viewer, which is not subject to CORS.
				if ( handledError ) {
					return;
				}

				handledError = true;

				root.unmount();
				wrapper.textContent = '';

				// Restore the server-rendered paragraph so renderNativeFallback() can hand it
				// to the <object> as its own fallback content, download link intact. A browser
				// that cannot display PDFs either then still offers the visitor the file,
				// rather than a sentence telling them it cannot be shown and nothing else.
				if ( serverFallback ) {
					wrapper.appendChild( serverFallback );
				}

				renderNativeFallback( wrapper, previewUrl );
			},
		} ),
	);
}

document.addEventListener( 'DOMContentLoaded', function() {
	const wrappers = document.querySelectorAll(
		'.godam-pdf-wrapper[data-godam-preview]',
	);

	if ( ! wrappers.length ) {
		return;
	}

	// Nothing is fetched until the document scrolls into view: a block far down a long page
	// should not cost every visitor a pdf.js download plus a multi-megabyte PDF.
	if ( ! ( 'IntersectionObserver' in window ) ) {
		wrappers.forEach( mountViewer );
		return;
	}

	const observer = new IntersectionObserver(
		( entries ) => {
			entries.forEach( ( entry ) => {
				if ( ! entry.isIntersecting ) {
					return;
				}

				observer.unobserve( entry.target );
				mountViewer( entry.target );
			} );
		},
		// Start loading just before the block reaches the viewport, so scrolling to it
		// usually finds it already rendered.
		{ rootMargin: '200px' },
	);

	wrappers.forEach( ( wrapper ) => observer.observe( wrapper ) );
} );
