import { Caption } from './caption';
import {
	ALLOWED_MEDIA_TYPES,
	DOCUMENT_ACCEPT,
	IN_PROGRESS_TRANSCODING_STATUSES,
	isSupportedDocument,
	isSupportedDocumentUrl,
} from './constants';
import './editor.scss';

// pdf.js is heavy, and most posts being edited contain no document at all. Loading it only
// when a document is actually on the canvas keeps it out of the editor's initial bundle —
// and it is the same chunk the front end uses, so it is usually already cached.
const DocumentViewer = lazy( () =>
	import( /* webpackChunkName: "godam-pdf-viewer" */ './viewer' ),
);

/**
 * Format bytes → human-readable KB / MB.
 *
 * @param {number} bytes - The number of bytes.
 *
 * @return {string} The formatted file size.
 */
function formatFileSize( bytes ) {
	if ( ! bytes ) {
		return '';
	}
	if ( bytes < 1024 * 1024 ) {
		return `${ Math.round( bytes / 1024 ) } KB`;
	}
	return `${ ( bytes / ( 1024 * 1024 ) ).toFixed( 1 ) } MB`;
}

/**
 * Edit component for the GoDAM Document block.
 *
 * @param {Object}   props                   - The properties passed to the component.
 * @param {Object}   props.attributes        - The block attributes.
 * @param {string}   props.className         - The class name for the component for styling.
 * @param {Function} props.setAttributes     - Function to update the block's attributes.
 * @param {boolean}  props.isSelected        - Whether the block is currently selected.
 * @param {Function} props.insertBlocksAfter - Function to insert blocks after the current block.
 *
 * @return {JSX.Element} The rendered document block component.
 */
function PdfEdit( {
	attributes,
	className,
	setAttributes,
	isSelected: isSingleSelected,
	insertBlocksAfter,
} ) {
	const {
		id,
		height,
		src,
		docTitle,
		description,
		previewMode,
		showCover,
		customCover,
		coverImages,
		pageCount,
	} = attributes;

	const [ temporaryURL, setTemporaryURL ] = useState( attributes.blob );
	// Track file info during upload so we can display a nice progress UI.
	const [ uploadingFile, setUploadingFile ] = useState( null );
	const { createErrorNotice, createWarningNotice } = useDispatch( noticesStore );

	// Fetch attachment metadata: auto-generated cover, file size, MIME type, and the
	// transcoding state needed to tell "preview on its way" from "there will never be one".
	const {
		autoGeneratedCover,
		fileSize,
		hasResolvedMedia,
		mimeType,
		previewPdfUrl,
		sourceUrl,
		transcodingStatus,
	} = useSelect(
		( select ) => {
			if ( ! id ) {
				// A document added by URL alone has no record to wait for.
				return {
					autoGeneratedCover: '',
					fileSize: 0,
					hasResolvedMedia: true,
					mimeType: '',
					previewPdfUrl: '',
					sourceUrl: '',
					transcodingStatus: '',
				};
			}
			const media = select( coreStore ).getEntityRecord( 'postType', 'attachment', id );
			return {
				/*
				 * Whether the record above has actually been fetched yet, as opposed to simply
				 * being absent. Every field here reads as empty until the request resolves, and
				 * an empty transcoding status is meaningful — it is what "no job was ever
				 * dispatched" looks like — so without this the canvas would classify the
				 * document from placeholder values and show the download-only panel for a moment
				 * before the real data arrived.
				 */
				hasResolvedMedia: select( coreStore ).hasFinishedResolution(
					'getEntityRecord',
					[ 'postType', 'attachment', id ],
				),
				// Mirror set_media_library_thumbnail(): check video thumbnail first (set by
				// GoDAM transcoding callback for WP-uploaded PDFs), then the PDF-specific key
				// (set by GoDAM tab import). Both are registered show_in_rest:true.
				autoGeneratedCover: media?.meta?.rtgodam_media_video_thumbnail ||
				media?.meta?.rtgodam_media_pdf_thumbnail ||
				'',
				fileSize: media?.media_details?.filesize || 0,
				mimeType: media?.mime_type || '',
				previewPdfUrl: media?.meta?.rtgodam_preview_pdf_url || '',
				// REST runs source_url through wp_get_attachment_url(), so GoDAM-tab media
				// resolves to its CDN URL here just as it does server-side.
				sourceUrl: media?.source_url || '',
				transcodingStatus: ( media?.meta?.rtgodam_transcoding_status || '' ).toLowerCase(),
			};
		},
		[ id ],
	);

	/*
	 * The PDF to render. Mirrors rtgodam_get_document_preview_url() on the server, so the
	 * canvas shows exactly what a visitor will see:
	 *
	 * - the preview PDF once Central has produced one;
	 * - for a plain PDF, the file itself, which needs no conversion and lets the editor
	 *   render immediately rather than waiting on a transcode.
	 *
	 * Anything else has nothing to show yet.
	 */
	const isPdfSource = mimeType
		? 'application/pdf' === mimeType
		: /\.pdf(?:[?#]|$)/i.test( src || '' );
	const resolvedPreviewUrl = previewPdfUrl || ( isPdfSource ? src : '' );

	/*
	 * The file to offer for download, mirroring rtgodam_get_document_download_url(). Always
	 * the original upload, never the generated preview — somebody who uploaded report.xlsx
	 * and got preview.pdf back will think something broke.
	 *
	 * The attachment's own URL wins over the stored `src`, which was captured when the block
	 * was inserted and can be stale if the file was later offloaded to a CDN.
	 */
	const resolvedDownloadUrl = sourceUrl || src || '';

	/**
	 * Record the page count reported by pdf.js.
	 *
	 * This replaces an earlier hand-rolled count that fetched the raw file and regex-scanned
	 * it for `/Count` entries. That could not see cross-origin CDN files (blocked by CORS)
	 * and missed PDF 1.5+ files whose page tree lives in a compressed object stream. pdf.js
	 * has already parsed the document properly by the time it tells us, so this is both
	 * cheaper and correct.
	 *
	 * Written only while the block is selected, and only when the number actually changes.
	 * Both guards matter: any attribute write during a passive page load flags the post as
	 * having unsaved changes, so an author who merely opened a post to read it would be met
	 * with the browser's "Leave site?" prompt. Blocks saved before pdf.js was introduced hold
	 * pageCount: 0 — the old counter could not read cross-origin files — so without the
	 * selection guard every one of them would rewrite itself on open.
	 *
	 * The count is therefore refreshed the moment the author touches the block, which is also
	 * the only point at which they could act on it.
	 *
	 * @param {Object} pdf pdf.js document proxy.
	 */
	function onPreviewLoaded( pdf ) {
		if ( ! isSingleSelected ) {
			return;
		}

		if ( pdf?.numPages > 0 && pdf.numPages !== pageCount ) {
			setAttributes( { pageCount: pdf.numPages } );
		}
	}

	function onUploadError( message ) {
		createErrorNotice( message, { type: 'snackbar' } );
	}

	function onSelectPdf( media ) {
		if ( ! media || ! media.url ) {
			setAttributes( {
				src: undefined,
				id: undefined,
				caption: undefined,
				blob: undefined,
			} );
			setTemporaryURL();
			setUploadingFile( null );
			return;
		}

		if ( isBlobURL( media.url ) ) {
			// An in-flight upload: the MIME type is not populated yet, so validation
			// is deferred to the follow-up call that carries the finished attachment.
			setTemporaryURL( media.url );
			// Capture file name + size so the upload UI can display them.
			setUploadingFile( {
				name: media.filename || media.title || __( 'Document', 'godam' ),
				size: media.filesizeInBytes || 0,
			} );
			return;
		}

		// Validate the format. The MediaUpload allowedTypes filter restricts the library UI,
		// but a runtime check is needed as a safety net (e.g. drag-and-drop bypasses it).
		// isSupportedDocument() prefers the MIME type and falls back to the extension, so an
		// unknown format is rejected rather than passed straight through.
		if ( ! isSupportedDocument( media ) ) {
			createWarningNotice(
				__( 'That file type is not supported. Choose a PDF, Word, Excel, PowerPoint, OpenDocument, TXT or CSV file.', 'godam' ),
				{ type: 'snackbar', isDismissible: true },
			);
			return;
		}

		// Normalize the description to a string. Library selections expose it as
		// a plain string, but freshly uploaded files come from the REST API where
		// `description` is an object ( { raw, rendered } ). Storing the object
		// would make React throw "Objects are not valid as a React child" when
		// the description is rendered.
		const mediaDescription = typeof media.description === 'string'
			? media.description
			: ( media.description?.raw ?? '' );

		setAttributes( {
			blob: undefined,
			src: media.url,
			id: media.id,
			caption: media.caption,
			docTitle: media.title || '',
			description: mediaDescription,
			pageCount: 0, // Reset so useEffect re-counts pages for the new file.
		} );
		setTemporaryURL();
		setUploadingFile( null );
	}

	function onRemoveDocument() {
		setAttributes( {
			src: undefined,
			id: undefined,
			caption: undefined,
			blob: undefined,
		} );
	}

	/**
	 * Appends newly selected images to coverImages and always selects
	 * the last newly added one.
	 *
	 * @param {any} medias The media object or array of media objects returned from the media library after selecting cover images.
	 */
	function onAddCoverImages( medias ) {
		const items = Array.isArray( medias ) ? medias : [ medias ];
		const existing = coverImages || [];
		const toAdd = items.filter( ( m ) => ! existing.find( ( c ) => c.id === m.id ) );
		if ( ! toAdd.length ) {
			return;
		}
		const newCovers = [ ...existing, ...toAdd.map( ( m ) => ( { url: m.url, id: m.id } ) ) ];
		// Always jump to the last newly uploaded cover.
		const last = newCovers[ newCovers.length - 1 ];
		setAttributes( {
			coverImages: newCovers,
			customCover: last.url,
			customCoverId: last.id,
		} );
	}

	function onSelectTile( url, covId ) {
		setAttributes( { customCover: url, customCoverId: covId } );
	}

	function onDeleteCoverImage( index ) {
		const newCovers = ( coverImages || [] ).filter( ( _, i ) => i !== index );
		const deleted = ( coverImages || [] )[ index ];
		const updates = { coverImages: newCovers };
		if ( customCover === deleted?.url ) {
			updates.customCover = autoGeneratedCover || newCovers[ 0 ]?.url || '';
			updates.customCoverId = autoGeneratedCover ? undefined : ( newCovers[ 0 ]?.id ?? undefined );
		}
		setAttributes( updates );
	}

	const isCardView = previewMode === 'card';
	const hasDocument = !! ( src || temporaryURL );

	// Content saved before the format was validated (or added by URL) can still hold an
	// unsupported file. The front end renders nothing for those, so flag it here rather than
	// showing an empty frame.
	//
	// Decided from the stored URL first, because that is the only signal available on the
	// very first render; the attachment's MIME type arrives asynchronously and overrides it
	// once present, since it is the authoritative answer.
	//
	// Trade-off: a supported file served from an extension-less URL is flagged until its MIME
	// arrives. Erring that way is deliberate — the opposite error would show the author a
	// broken preview and imply the page is fine.
	const isUnsupported = hasDocument && ! temporaryURL && (
		mimeType
			? ! ALLOWED_MEDIA_TYPES.includes( mimeType )
			: ! isSupportedDocumentUrl( src || '' )
	);

	/*
	 * No preview yet. Two situations, and the author needs to be able to tell them apart
	 * because only one of them resolves on its own:
	 *
	 * - a transcoding job is in flight — a preview is coming, so the canvas says so and the
	 *   author has no reason to go looking for a fix;
	 * - no job is running, so no preview is coming. Either one finished without producing
	 *   anything (it failed, or the document is password protected — GoDAM Central stores
	 *   those as-is and reports success, because it cannot convert a file it cannot open), or
	 *   one was never dispatched at all, which is what an absent status means. A visitor sees
	 *   the download-only panel in every one of those cases, so the canvas shows that same
	 *   panel rather than inventing editor-only copy for a distinction the page does not draw.
	 *
	 * Judged by an allow-list of in-flight statuses, so an absent status and anything
	 * unrecognised land in the second bucket rather than promising a preview forever.
	 */
	const missingPreview =
		hasDocument && ! temporaryURL && ! isUnsupported && ! resolvedPreviewUrl;
	/*
	 * Nothing can be classified until the attachment record has been fetched: until then every
	 * field reads empty, which is indistinguishable from a document that genuinely has no
	 * preview. Judging it early made the block open on the download-only panel and then swap to
	 * the document a moment later. Show the same "Loading preview…" the viewer itself uses, so
	 * the wait reads as one continuous load rather than a wrong answer being corrected.
	 */
	const isResolvingMedia = missingPreview && ! hasResolvedMedia;
	const isAwaitingPreview =
		missingPreview && ! isResolvingMedia &&
		IN_PROGRESS_TRANSCODING_STATUSES.includes( transcodingStatus );
	const hasNoPreview = missingPreview && ! isResolvingMedia && ! isAwaitingPreview;

	const classes = clsx( className, {
		'is-transient': !! temporaryURL,
		[ `is-preview-${ previewMode || 'default' }` ]: true,
	} );

	const blockProps = useBlockProps( { className: classes } );

	// Derive a short display name from the URL.
	const fileName = src
		? src.split( '/' ).pop().split( '?' )[ 0 ]
		: __( 'Document', 'godam' );

	// ── Empty state ───────────────────────────────────────────────────────────
	if ( ! hasDocument ) {
		return (
			<>
				<InspectorControls>
					<PanelBody title={ __( 'Doc Selection', 'godam' ) } initialOpen={ true }>
						<p className="godam-pdf-panel-description">
							{ __( 'Add title, description, and more to make your document stand out.', 'godam' ) }
						</p>
						<MediaUploadCheck>
							<MediaUpload
								onSelect={ onSelectPdf }
								allowedTypes={ ALLOWED_MEDIA_TYPES }
								accept={ DOCUMENT_ACCEPT }
								render={ ( { open } ) => (
									<Button
										__next40pxDefaultSize
										variant="secondary"
										onClick={ open }
										className="godam-pdf__add-document-btn"
										data-test-id="godam-pdf-button-add-document"
									>
										{ __( '+ Add Document', 'godam' ) }
									</Button>
								) }
							/>
						</MediaUploadCheck>
					</PanelBody>
				</InspectorControls>

				<figure { ...blockProps } data-test-id="godam-pdf-canvas-placeholder">
					<div className="godam-pdf-empty">
						<h3 className="godam-pdf-empty__title">
							{ __( 'Attach a document here', 'godam' ) }
						</h3>
						<p className="godam-pdf-empty__subtitle">
							{ __( 'Upload a PDF, Word, Excel, PowerPoint, OpenDocument, TXT or CSV file to embed it or display it as a card with a cover image.', 'godam' ) }
						</p>
						<MediaUploadCheck>
							<MediaUpload
								onSelect={ onSelectPdf }
								allowedTypes={ ALLOWED_MEDIA_TYPES }
								accept={ DOCUMENT_ACCEPT }
								render={ ( { open } ) => (
									<Button
										variant="primary"
										onClick={ open }
										className="godam-pdf-empty__btn"
										data-test-id="godam-pdf-button-select"
									>
										{ __( '+ Upload Document', 'godam' ) }
									</Button>
								) }
							/>
						</MediaUploadCheck>
					</div>
				</figure>
			</>
		);
	}

	// ── Uploading state ───────────────────────────────────────────────────────
	if ( temporaryURL ) {
		return (
			<figure { ...blockProps }>
				<div className="godam-pdf-uploading" data-test-id="godam-pdf-content-uploading">
					<div className="godam-pdf-uploading__card">
						<span className="godam-pdf-uploading__icon dashicons dashicons-upload" />
						<div className="godam-pdf-uploading__details">
							<span className="godam-pdf-uploading__name">
								{ uploadingFile?.name || __( 'Document', 'godam' ) }
							</span>
							{ uploadingFile?.size > 0 && (
								<span className="godam-pdf-uploading__size">
									{ formatFileSize( uploadingFile.size ) }
								</span>
							) }
							<div className="godam-pdf-uploading__bar-track">
								<div className="godam-pdf-uploading__bar-fill" />
							</div>
						</div>
					</div>
				</div>
			</figure>
		);
	}

	// ── Editor canvas: unsupported format ─────────────────────────────────────
	const UnsupportedCanvas = (
		<div className="godam-pdf-unsupported" data-test-id="godam-pdf-content-unsupported">
			<span className="godam-pdf-unsupported__icon dashicons dashicons-media-document" />
			<h3 className="godam-pdf-unsupported__title">
				{ __( 'Unsupported file format', 'godam' ) }
			</h3>
			<p className="godam-pdf-unsupported__desc">
				{ __( 'Replace this with a PDF, Word, Excel, PowerPoint, OpenDocument, TXT or CSV file; it will not be shown on your page.', 'godam' ) }
			</p>
			<p className="godam-pdf-unsupported__file">{ fileName }</p>
		</div>
	);

	// ── Editor canvas: preview still being generated ──────────────────────────
	// Editor-only: the front end has no "wait for it" state, it just offers the download
	// until a preview exists. The author is the one who needs to know a preview is coming,
	// so this replaces the download-only panel on the canvas — but still offers the original,
	// which is exactly what a visitor gets in the meantime.
	const ProcessingCanvas = (
		<div className="godam-pdf-processing" data-test-id="godam-pdf-content-processing">
			<span className="godam-pdf-processing__icon dashicons dashicons-update" />
			<h3 className="godam-pdf-processing__title">
				{ __( 'Generating preview…', 'godam' ) }
			</h3>
			<p className="godam-pdf-processing__desc">
				{ __( 'GoDAM is converting this document so it can be displayed on your page. Until it is ready, visitors are offered the original as a download. Reload this post to check for the finished preview.', 'godam' ) }
			</p>
			<p className="godam-pdf-processing__file">{ fileName }</p>
			{ resolvedDownloadUrl && (
				<a
					className="godam-pdf-processing__download"
					href={ resolvedDownloadUrl }
					target="_blank"
					rel="noopener noreferrer"
				>
					{ __( 'Download original', 'godam' ) }
				</a>
			) }
		</div>
	);

	// ── Editor canvas: no preview will ever exist ─────────────────────────────
	// Deliberately the same markup, classes and copy as render.php's empty-preview branch,
	// styled by the shared style.scss that the editor loads too. The author sees the real
	// thing rather than an editor-only approximation of it.
	const UnavailableCanvas = (
		<div className="godam-pdf-unavailable" data-test-id="godam-pdf-content-unavailable">
			<span className="dashicons dashicons-media-document" aria-hidden="true" />
			<p className="godam-pdf-unavailable__text">
				{ __( 'A preview is not available for this document.', 'godam' ) }
			</p>
			{ resolvedDownloadUrl && (
				<a
					className="godam-pdf-unavailable__download"
					href={ resolvedDownloadUrl }
					target="_blank"
					rel="noopener noreferrer"
				>
					{ __( 'Download original', 'godam' ) }
				</a>
			) }
		</div>
	);

	/*
	 * ── Editor canvas: waiting on the attachment record ───────────────────────
	 *
	 * Same container and same copy as the viewer's own loading state, so resolving the record
	 * and then loading the PDF read as one uninterrupted wait with no swap and no layout shift.
	 */
	const LoadingPreviewCanvas = (
		<div
			className="godam-pdf-preview godam-pdf-preview--default"
			style={ { height: `${ height }px` } }
			data-test-id="godam-pdf-content-loading"
		>
			<p className="godam-pdf-viewer__message">
				{ __( 'Loading preview…', 'godam' ) }
			</p>
		</div>
	);

	/*
	 * ── Editor canvas: Default View (rendered PDF) ────────────────────────────
	 *
	 * Deliberately NOT wrapped in <Disabled>, which is the usual way to stop an embedded
	 * preview swallowing editor clicks. <Disabled> works by setting `pointer-events: none`,
	 * and that takes the wheel with it — the preview became unscrollable in the editor
	 * whenever the block was not selected, which is not how it behaves on the page.
	 *
	 * Nothing here needs disabling anyway. The annotation layer is off, so there are no
	 * links or form fields, and the text layer is off in the editor (below), so the only
	 * thing under the cursor is a canvas. Canvases do not swallow mousedown, so clicking
	 * the preview still selects the block exactly as it would on any other block.
	 *
	 * Trade-off: with the cursor over the preview the wheel scrolls the document rather
	 * than the post. That is the same scroll-trap the front end has, which is the point.
	 */
	const DefaultViewCanvas = (
		<div
			className="godam-pdf-preview godam-pdf-preview--default"
			style={ { height: `${ height }px` } }
			data-test-id="godam-pdf-content-preview-default"
		>
			<Suspense
				fallback={
					<p className="godam-pdf-viewer__message">
						{ __( 'Loading preview…', 'godam' ) }
					</p>
				}
			>
				<DocumentViewer
					url={ resolvedPreviewUrl }
					title={ docTitle || fileName }
					onLoadSuccess={ onPreviewLoaded }
					// The text layer exists so visitors can select, copy and find text. In the
					// editor it would only intercept clicks meant to select the block, and it is
					// invisible either way, so the rendering is identical without it.
					renderTextLayer={ false }
				/>
			</Suspense>
		</div>
	);

	// ── Editor canvas: Card View ──────────────────────────────────────────────
	// Only show a cover when the toggle is on.
	const effectiveCover = showCover ? ( customCover || autoGeneratedCover || '' ) : '';

	// Format metadata line: "4 pages • 140 KB"
	const metaParts = [
		pageCount ? `${ pageCount } ${ pageCount === 1 ? __( 'page', 'godam' ) : __( 'pages', 'godam' ) }` : '',
		formatFileSize( fileSize ),
	].filter( Boolean );
	const metaLine = metaParts.join( ' • ' );

	const CardViewCanvas = (
		<div className="godam-pdf-preview godam-pdf-preview--card" data-test-id="godam-pdf-content-preview-card">
			<div className="godam-pdf-card">
				<div className="godam-pdf-card__cover">
					{ effectiveCover ? (
						<img
							src={ effectiveCover }
							alt={ docTitle || __( 'Document cover', 'godam' ) }
						/>
					) : (
						<div className="godam-pdf-card__cover-placeholder">
							<span className="dashicons dashicons-media-document" />
						</div>
					) }
				</div>
				<div className="godam-pdf-card__info">
					<p className="godam-pdf-card__title">
						{ docTitle || fileName }
					</p>
					{ description && (
						<p className="godam-pdf-card__description">{ description }</p>
					) }
					<p className="godam-pdf-card__meta">
						{ metaLine || fileName }
					</p>
				</div>
			</div>
		</div>
	);

	// Resolved before the JSX. An unsupported file wins over everything, since neither preview
	// can represent it. Card view comes next — it shows a cover rather than the document, so
	// it stays accurate while a preview is still being generated. Only the default view has
	// to care about whether a renderable PDF exists yet.
	let canvasContent = DefaultViewCanvas;
	if ( isUnsupported ) {
		canvasContent = UnsupportedCanvas;
	} else if ( isCardView ) {
		canvasContent = CardViewCanvas;
	} else if ( isResolvingMedia ) {
		// Ahead of the two states below: neither can be judged until the record has arrived.
		canvasContent = LoadingPreviewCanvas;
	} else if ( isAwaitingPreview ) {
		canvasContent = ProcessingCanvas;
	} else if ( hasNoPreview ) {
		canvasContent = UnavailableCanvas;
	}

	return (
		<>
			{ /* ── Toolbar ─────────────────────────────────────────────────── */ }
			{ isSingleSelected && (
				<BlockControls group="other">
					<MediaReplaceFlow
						mediaId={ id }
						mediaURL={ src }
						allowedTypes={ ALLOWED_MEDIA_TYPES }
						accept={ DOCUMENT_ACCEPT }
						onSelect={ onSelectPdf }
						onError={ onUploadError }
						onReset={ () => onSelectPdf( undefined ) }
					/>
				</BlockControls>
			) }

			{ /* ── Inspector ─────────────────────────────────────────────────── */ }
			<InspectorControls>

				{ /* Doc Selection */ }
				<PanelBody title={ __( 'Doc Selection', 'godam' ) } initialOpen={ true } data-test-id="godam-pdf-panel-selection">
					<p className="godam-pdf-panel-description">
						{ __( 'Add title, description, and more to make your document stand out.', 'godam' ) }
					</p>

					<div className="godam-pdf-file-row">
						<span className="godam-pdf-file-row__icon dashicons dashicons-media-document" />
						<span className="godam-pdf-file-row__name" title={ fileName }>
							{ fileName }
						</span>
						<Button
							icon={ trash }
							label={ __( 'Remove document', 'godam' ) }
							isDestructive
							size="small"
							onClick={ onRemoveDocument }
							data-test-id="godam-pdf-button-remove-document"
						/>
					</div>

					<TextControl
						__next40pxDefaultSize
						__nextHasNoMarginBottom
						label={ __( 'Doc Title', 'godam' ) }
						value={ docTitle }
						placeholder={ __( 'Add document title', 'godam' ) }
						onChange={ ( value ) => setAttributes( { docTitle: value } ) }
						data-test-id="godam-pdf-control-doc-title"
					/>

					<TextareaControl
						__nextHasNoMarginBottom
						label={ __( 'Description', 'godam' ) }
						value={ description }
						placeholder={ __( 'Add document description', 'godam' ) }
						rows={ 4 }
						onChange={ ( value ) => setAttributes( { description: value } ) }
						data-test-id="godam-pdf-control-description"
					/>
				</PanelBody>

				{ /* Preview */ }
				<PanelBody title={ __( 'Preview', 'godam' ) } initialOpen={ true } data-test-id="godam-pdf-panel-preview">
					<ToggleGroupControl
						__nextHasNoMarginBottom
						isBlock
						label={ __( 'View', 'godam' ) }
						hideLabelFromVision
						value={ previewMode || 'default' }
						onChange={ ( value ) => value && setAttributes( { previewMode: value } ) }
						data-test-id="godam-pdf-control-view-mode"
					>
						<ToggleGroupControlOption
							value="default"
							label={ __( 'Default View', 'godam' ) }
						/>
						<ToggleGroupControlOption
							value="card"
							label={ __( 'Card View', 'godam' ) }
						/>
					</ToggleGroupControl>

					{ isCardView && (
						<>
							<ToggleControl
								__nextHasNoMarginBottom
								label={ __( 'Show cover', 'godam' ) }
								checked={ !! showCover }
								onChange={ ( value ) => setAttributes( { showCover: value } ) }
								data-test-id="godam-pdf-control-show-cover"
							/>

							{ showCover && (
								<div className="godam-pdf-custom-cover">
									<p className="godam-pdf-panel-sublabel">
										{ __( 'Cover', 'godam' ) }
									</p>

									<div className="godam-pdf-covers-list">

										{ /* Tile 0: auto-generated */ }
										<button
											type="button"
											className={ `godam-pdf-cover-tile${ ( customCover === autoGeneratedCover || ! customCover ) ? ' is-selected' : '' }` }
											onClick={ () => onSelectTile( autoGeneratedCover, undefined ) }
											title={ __( 'Auto-generated cover', 'godam' ) }
											data-test-id="godam-pdf-button-cover-auto"
										>
											{ autoGeneratedCover ? (
												<img src={ autoGeneratedCover } alt={ __( 'Auto-generated', 'godam' ) } />
											) : (
												<div className="godam-pdf-cover-tile__placeholder">
													<span className="dashicons dashicons-media-document" />
												</div>
											) }
											{ /* 4-pointed sparkle badge */ }
											<span className="godam-pdf-cover-tile__badge" aria-hidden="true">
												<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor" width="16" height="16">
													<path d="M12 2 Q13 10 22 12 Q13 14 12 22 Q11 14 2 12 Q11 10 12 2Z" />
												</svg>
											</span>
											{ ( customCover === autoGeneratedCover || ! customCover ) && (
												<span className="godam-pdf-cover-tile__check" aria-hidden="true">
													<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" width="20" height="20">
														<circle cx="10" cy="10" r="10" fill="var(--wp-admin-theme-color,#3858e9)" />
														<polyline points="5,10 8.5,13.5 15,7" fill="none" stroke="#fff" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
													</svg>
												</span>
											) }
										</button>

										{ /* User-uploaded tiles */ }
										{ /* Tile wrapper uses div+role="button" so the delete <button> is a
										     valid child — nested <button> inside <button> is invalid HTML
										     and causes the browser to reparent the inner element, breaking
										     stopPropagation and React's validateDOMNesting. */ }
										{ ( coverImages || [] ).map( ( cover, i ) => (
											<div
												key={ cover.id || i }
												role="button"
												tabIndex={ 0 }
												className={ `godam-pdf-cover-tile${ customCover === cover.url ? ' is-selected' : '' }` }
												aria-label={ __( 'Select cover image', 'godam' ) }
												data-test-id={ `godam-pdf-element-cover-tile-${ cover.id }` }
												onClick={ () => onSelectTile( cover.url, cover.id ) }
												onKeyDown={ ( e ) => {
													if ( e.key === 'Enter' || e.key === ' ' ) {
														e.preventDefault();
														onSelectTile( cover.url, cover.id );
													}
												} }
											>
												<img src={ cover.url } alt="" />
												{ customCover === cover.url && (
													<span className="godam-pdf-cover-tile__check" aria-hidden="true">
														<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" width="20" height="20">
															<circle cx="10" cy="10" r="10" fill="var(--wp-admin-theme-color,#3858e9)" />
															<polyline points="5,10 8.5,13.5 15,7" fill="none" stroke="#fff" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
														</svg>
													</span>
												) }
												<button
													type="button"
													className="godam-pdf-cover-tile__delete"
													aria-label={ __( 'Remove cover', 'godam' ) }
													onClick={ ( e ) => {
														e.stopPropagation();
														onDeleteCoverImage( i );
													} }
													data-test-id={ `godam-pdf-button-cover-delete-${ cover.id }` }
												>
													<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" width="8" height="8">
														<line x1="1" y1="1" x2="11" y2="11" stroke="currentColor" strokeWidth="2" strokeLinecap="round" />
														<line x1="11" y1="1" x2="1" y2="11" stroke="currentColor" strokeWidth="2" strokeLinecap="round" />
													</svg>
												</button>
											</div>
										) ) }

									</div>

									<MediaUploadCheck>
										<MediaUpload
											onSelect={ onAddCoverImages }
											allowedTypes={ [ 'image' ] }
											multiple
											render={ ( { open } ) => (
												<Button
													__next40pxDefaultSize
													variant="secondary"
													onClick={ open }
													className="godam-pdf__upload-cover-btn"
													data-test-id="godam-pdf-button-upload-cover"
												>
													{ __( '+ Add Cover', 'godam' ) }
												</Button>
											) }
										/>
									</MediaUploadCheck>
									<p className="godam-pdf-panel-hint">
										{ __( 'Recommended aspect ratio: 16:9.', 'godam' ) }
									</p>
								</div>
							) }
						</>
					) }
				</PanelBody>

				{ /* Height — only in default embed view */ }
				{ ! isCardView && (
					<PanelBody title={ __( 'Height', 'godam' ) } initialOpen={ true } data-test-id="godam-pdf-panel-settings">
						<RangeControl
							__nextHasNoMarginBottom
							label={ __( 'Height (px)', 'godam' ) }
							hideLabelFromVision
							value={ height }
							onChange={ ( value ) => setAttributes( { height: value } ) }
							min={ 200 }
							max={ 1200 }
							step={ 10 }
							data-test-id="godam-pdf-control-height"
						/>
					</PanelBody>
				) }

			</InspectorControls>

			{ /* ── Block canvas ─────────────────────────────────────────────── */ }
			<figure { ...blockProps } data-test-id="godam-pdf-canvas">
				{ canvasContent }
				<Caption
					attributes={ attributes }
					setAttributes={ setAttributes }
					isSelected={ isSingleSelected }
					insertBlocksAfter={ insertBlocksAfter }
					showToolbarButton={ isSingleSelected }
				/>
			</figure>
		</>
	);
}

export default PdfEdit;
